export const Route = createFileRoute("/gallery")({
  head: () => ({
    meta: [
      { title: "Certificate Gallery | 10 Minute School" },
      {
        name: "description",
        content:
          "Browse every result certificate generated by 10 Minute School students. Filter by class or search by student and school name.",
      },
      { property: "og:title", content: "Certificate Gallery | 10 Minute School" },
      {
        property: "og:description",
        content:
          "Browse all student result certificates. Filter by class, search by name or school.",
      },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: GalleryPage,
});

const CLASS_FILTERS = ["All", "Class 6", "Class 7", "Class 8", "Class 9", "Class 10"];

